# First class
class Dog:
    def sound(self):
        print("Dog barks")

# Second class
class Cat:
    def sound(self):
        print("Cat meows")

# Third class
class Cow:
    def sound(self):
        print("Cow moos")

# Creating objects
d = Dog()
c = Cat()
w = Cow()

d.sound()
c.sound()
w.sound()
